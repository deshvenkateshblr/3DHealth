#!/usr/bin/env node
/* Builds shared/data.videotopics.js (video id -> app topics) and tools/video_topics_audit.csv
   from the video data files plus tools/video_topic_rules.js.  Usage: node tools/build_video_topics.js */
const fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..');
global.window = {};
for (const f of ['data.symptoms.js', 'data.videos.sb.js', 'data.videos.nbs.js', 'drsk_video_data.js', 'ayushyp_video_data.js', 'curated_routine_video_data.js'])
  eval(fs.readFileSync(path.join(root, 'shared', f), 'utf8'));
const RULES = require('./video_topic_rules.js');
const SOURCES = { SB: window.SB_VIDEOS, NBS: window.NBS_VIDEOS, DRSK: window.DRSUMIT_VIDEOS, AYUSH: window.AYUSH_VIDEOS, CUR: window.CURATED_VIDEOS };

const re = list => list && list.length ? new RegExp('(?<![a-z0-9])(?:' + list.join('|') + ')', 'i') : null;
const compiled = {};
for (const [topic, r] of Object.entries(RULES)) compiled[topic] = { kw: re(r.kw), not: re(r.not), tr: re(r.tradition) };

// Broad topics that channels attach to many unrelated videos as search tags.
const SPAM_PRONE = new Set(['Weight Loss', 'Overweight', 'Diabetes', 'Blood Sugar', 'Insulin Resistance', 'Healthy Eating', 'Sugar',
  'Stress', 'Beginner Workout', 'Poor Circulation', 'Immune Weakness', 'Belly Fat', 'Ultra-Processed Foods', 'Gut Health']);
function analyse(v) {
  const title = v.title || '', tags = v.tags || [], desc = v.description_short || '';
  const out = {};
  for (const [topic, c] of Object.entries(compiled)) {
    const ev = [];
    if (c.kw && c.kw.test(title) && !(c.not && c.not.test(title))) ev.push(['title', title.match(c.kw)[0]]);
    const tagHits = c.kw ? tags.filter(t => c.kw.test(t) && !(c.not && c.not.test(t))) : [];
    if (tagHits.length) ev.push(['tag', tagHits.slice(0, 3).join(' / '), tagHits.length]);
    if (c.tr && c.tr.test(title)) ev.push(['tradition', title.match(c.tr)[0]]);
    if (c.kw && c.kw.test(desc) && !(c.not && c.not.test(desc))) ev.push(['desc', desc.match(c.kw)[0]]);
    if (!ev.length) continue;
    let level = 'low';
    const has = k => ev.find(e => e[0] === k);
    if (has('title')) level = 'high';
    else if (has('tradition')) level = 'medium-tradition';
    else if (has('tag')) {
    // Many channels stuff tags for search, so a lone tag is weak evidence. Accept: 3+ agreeing tags, or
    // 2+ for ordinary topics, or 1 tag that names the topic itself (e.g. "stretching exercises for back pain").
    const n = has('tag')[2], names = has('tag')[1].toLowerCase().includes(topic.toLowerCase());
    const spammy = SPAM_PRONE.has(topic);
    if (n >= 3 || (!spammy && (n >= 2 || names))) level = 'medium';
  }
    out[topic] = { level, ev };
  }
  return out;
}

const mapping = {}, rows = [['source', 'video_id', 'title', 'topic', 'confidence', 'used_in_app', 'evidence']];
const counts = { high: 0, medium: 0, 'medium-tradition': 0, low: 0 };
const perTopic = {}; let videos = 0, unmapped = 0;
for (const [src, list] of Object.entries(SOURCES)) for (const v of list) {
  videos++;
  const res = analyse(v); const used = [];
  for (const [topic, r] of Object.entries(res)) {
    counts[r.level]++;
    const use = r.level !== 'low';
    if (use) { used.push([topic, r.level === 'high' ? 3 : 2]); perTopic[topic] = (perTopic[topic] || 0) + 1; }
    rows.push([src, v.id, v.title, topic, r.level, use ? 'yes' : 'no', r.ev.map(e => e[0] + ':' + e[1]).join(' | ')]);
  }
  if (used.length) mapping[v.id] = (mapping[v.id] || []).concat(used); else unmapped++;
}
const q = s => '"' + String(s == null ? '' : s).replace(/"/g, '""') + '"';
fs.writeFileSync(path.join(__dirname, 'video_topics_audit.csv'), rows.map(r => r.map(q).join(',')).join('\n'));
fs.writeFileSync(path.join(root, 'shared', 'data.videotopics.js'),
  '/* GENERATED by tools/build_video_topics.js from tools/video_topic_rules.js. Do not edit by hand.\n   video id -> [[topic, strength]]  (3 = in the title, 2 = in several tags or a named practice) */\nwindow.VIDEO_TOPICS = ' + JSON.stringify(mapping) + ';\n');

const symptoms = [...new Set(window.SYMPTOM_CATEGORIES.flatMap(c => c.items))];
const ctx = ['Menopause', 'PCOS', 'Weight Loss', 'Belly Fat', 'Blood Sugar', 'Insulin Resistance', 'Sugar', 'Ultra-Processed Foods', 'Healthy Eating', 'Sleep', 'Beginner Workout'];
console.log(`videos ${videos} | mapped ${videos - unmapped} | unmapped ${unmapped}`);
console.log('assignments by confidence', JSON.stringify(counts));
const none = symptoms.filter(t => !perTopic[t]);
console.log(`symptoms with no video (${none.length}/${symptoms.length}):`, none.join(', '));
console.log('context tags with no video:', ctx.filter(t => !perTopic[t]).join(', ') || 'none');
console.log('videos per topic (top 15):', Object.entries(perTopic).sort((a, b) => b[1] - a[1]).slice(0, 15).map(x => x[0] + ':' + x[1]).join('  '));
